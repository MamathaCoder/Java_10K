package com.coders.files;

public class Systemerr {
	public static void main(String[] args) {
		
		//using print()
		System.err.print("This is an error message using print().ln");
		
	   //using println()
		System.err.println("This is an error message using println().ln");
		
	   //using printf()
		System.err.printf("This is an error message using printf().ln");
	}

}
